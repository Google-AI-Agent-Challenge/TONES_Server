    # H&B 특화 소스 및 피부타입 매핑
    sources = ["올리브영 온/오프라인", "화해 쇼핑", "글로우픽 뷰티스토어", "네이버 뷰티윈도", "쿠팡 뷰티스토어"]
    
    # reviewer_type으로 피부 타입 대입
    reviewer_types = ["지성 피부", "건성 피부", "민감성 피부", "복합성 피부", "수부지(수분부족형지성) 피부"]
    
    # issue_type으로 뷰티 특화 불편사항 대입
    issue_types = ["트러블/여드름", "끈적임", "건조함/속당김", "백탁/밀림", "배송지연/파손", "향/인공취", "유통기한", "용기불량/파손", None]

    # 1000개의 리뷰 루프 생성
    for i in range(1000):
        # 뷰티는 보통 5점과 4점에 평점이 집중되므로 가중치를 더 자연스럽게 설계 (5점: 42%, 4점: 33%, 3점: 13%, 2점: 8%, 1점: 4%)
        rating = random.choices([5, 4, 3, 2, 1], weights=[42, 33, 13, 8, 4])[0]
        p_id = random.choice(product_ids)
        r_uuid = str(uuid.uuid4())
        
        # 별점에 매칭되는 한글 뷰티 리뷰 샘플 획득
        review_sample = random.choice(reviews_pool[rating])
        text_raw, keywords_str, summary_raw = review_sample
        
        # 뷰티 리뷰 특화 어미 추가 변환 (자연스러운 한국어 구어체 느낌 가공)
        suffixes = ["", " 진짜 강추합니다!!", " 피부 결이 진짜 보들보들해져요.", " 대용량 개이득~", " 무난무난해서 쓰기 딱이에요.", " 가격 대비 괜찮은 편.", " 다음번엔 굳이 안 살 듯요.", " 민감성이신 분들 피하세요ㅠ"]
        suffix = suffixes[0]
        if rating >= 4:
            suffix = random.choice(suffixes[:4])
        elif rating == 3:
            suffix = random.choice(suffixes[4:6])
        else:
            suffix = random.choice(suffixes[6:])
            
        review_text = (text_raw + suffix).replace("'", "''")
        ai_summary = (summary_raw + (" 만족" if rating >= 4 else " 불만족")).replace("'", "''")
        
        # 감성(Sentiment) 정보 산정
        if rating >= 4:
            sentiment = "positive"
            sentiment_score = round(random.uniform(0.68, 0.99), 2)
        elif rating == 3:
            sentiment = "neutral"
            sentiment_score = round(random.uniform(-0.15, 0.15), 2)
        else:
            sentiment = "negative"
            sentiment_score = round(random.uniform(-0.99, -0.65), 2)
            
        source = random.choice(sources)
        rev_type = random.choice(reviewer_types)
        rev_type_val = f"'{rev_type}'"
        
        # 키워드 array 가공
        keyword_list = keywords_str.split(",")
        kw_sql = "ARRAY[" + ", ".join([f"'{k}'" for k in keyword_list]) + "]"
        
        # 무작위 리뷰 날짜 생성 (최근 90일 이내)
        days_ago = random.randint(0, 90)
        review_date = (datetime.now() - timedelta(days=days_ago)).strftime("%Y-%m-%d")
        created_at_val = (datetime.now() - timedelta(days=days_ago, hours=random.randint(1, 23))).strftime("%Y-%m-%d %H:%M:%S")
        
        issue = random.choice(issue_types) if rating <= 3 else None
        issue_val = f"'{issue}'" if issue else "NULL"
        
        review_id = str(uuid.uuid4())
        
        sql_lines.append(
            f"INSERT INTO public.reviews (id, product_id, source, reviewer_type, review_text, rating, review_date, sentiment, sentiment_score, keywords, issue_type, ai_summary, created_at, review_id) "
            f"VALUES ('{r_uuid}', '{p_id}', '{source}', {rev_type_val}, '{review_text}', {rating}, '{review_date}', '{sentiment}', {sentiment_score}, {kw_sql}, {issue_val}, '{ai_summary}', '{created_at_val}', '{review_id}');"
        )
        
    # 저장 경로 확보
    target_dir = os.path.dirname(os.path.abspath(__file__))
    project_root = os.path.dirname(target_dir) 
    output_path = os.path.join(project_root, "mock_data.sql")
    
    with open(output_path, "w", encoding="utf-8") as f:
        f.write("\n".join(sql_lines))
        
    print(f"[MockDataGenerator] 성공적으로 H&B 뷰티/화장품 특화 Mock 데이터를 1000개 생성하여 파일로 저장했습니다: {output_path}")
    return output_path

